// -------------------- LIDAR Functions --------------------
// -------------------- LIDAR: Take Range --------------------
void LIDAR_TakeRange(void) {
	 /*
	  * Send a measurement command to the LIDAR sensor over I2C.
	  *
	  * cmd[0] = 0x00
	  *   - Command/register pointer indicating a measurement operation
	  *
	  * cmd[1] = 0x04
	  *   - Measurement mode selection
	  *   - Typically enables bias correction (more accurate but slightly slower)
	  *
	  * The full 2-byte packet is transmitted to the LIDAR to initiate
	  * a new distance measurement cycle.
	  */

	uint8_t cmd[2] = {0x00, 0x04};
	I2CB1_Send(LIDAR_ADDR, cmd, 2);
}

// -------------------- LIDAR: Read Distance --------------------
uint16_t LIDAR_ReadDistance(void) {
	// LIDAR register address being accessed.
	// 0x8F is typically the distance measurement result register
	// (or a read pointer depending on the LIDAR model).
	uint8_t reg = 0x8F;

	// Buffer to store the 2-byte response from the LIDAR.
	// buf[0] = high byte (MSB)
	// buf[1] = low byte (LSB)
	uint8_t buf[2];

    // Send the register address (0x8F) to the LIDAR over I2C.
    // This tells the sensor: "I want to read from this register next."
    I2CB1_Send(LIDAR_ADDR, &reg, 1);

    // Wait for the LIDAR to complete its internal measurement and
    // prepare the result in its output registers.
    // 30 ms is a simple fixed delay instead of checking a "busy" flag.
    Clock_Delay1ms(30);

    // Read 2 bytes from the LIDAR starting at the previously set register.
    // buf[0] = high byte, buf[1] = low byte of the distance measurement.
    I2CB1_Recv(LIDAR_ADDR, buf, 2);

    // Combine the two 8-bit values into a single 16-bit distance value:
    // - buf[0] is the MSB (most significant byte)
    // - buf[1] is the LSB (least significant byte)
    return ((uint16_t)buf[0] << 8) | buf[1];
}

// -------------------- LIDAR: Full Measurement --------------------
uint16_t LIDAR_GetMeasurement(void) {
	 /*
	 * This function triggers a LIDAR distance measurement and returns
	 * the resulting 16-bit distance value.
	 *
	 * It works in two steps:
	 * 1. Send a command over I2C to start a measurement
	 * 2. Wait for the sensor to complete the measurement
	 * 3. Read back the computed distance
	 */

	uint8_t data[2];

	/*
	 * Build the I2C command packet:
	 * data[0] = command/register pointer (0x00)
	 * data[1] = measurement mode selection
	 *           0x03 = no bias correction (faster, less accurate)
	 */
	data[0] = 0x00;
	data[1] = 0x03;

	/*
	 * Send measurement command to LIDAR over I2C.
	 * This tells the sensor to begin taking a distance reading.
	 */
	I2CB1_Send(LIDAR_ADDR, data, 2);

	/*
	 * Wait for measurement to complete.
	 * The LIDAR needs time to fire the laser, process return signal,
	 * and update its internal result registers.
	 */
	Clock_Delay1ms(30);

	/*
	 * Read the most recent distance measurement from the sensor.
	 * Returns a 16-bit value formed from two 8-bit registers.
	 */
	return LIDAR_ReadDistance();
}

// -------------------- LIDAR: Stable Measurements --------------------
uint16_t GetStableDistance(void) {
	 /*
	 * This function improves LIDAR reliability by taking multiple
	 * measurements and averaging only valid readings.
	 *
	 * Purpose:
	 * - Reduce noise and occasional bad I2C reads
	 * - Improve stability for robot decision-making
	 */

	uint32_t sum = 0;   // Accumulates valid distance readings
	int valid = 0;      // Counts how many readings passed filtering
	int i;

	/*
	 * Take 5 consecutive LIDAR measurements
	 * Small delay between samples allows sensor settling
	 */
	for (i = 0; i < 5; i++)
	{
		uint16_t d = LIDAR_GetMeasurement();

		/*
		 * Filter out invalid or noisy readings:
		 * - 0 usually means no return / error
		 * - values > 400 are out of expected range (too far / garbage)
		 */
		if (d > 0 && d < 400)
		{
			sum += d;
			valid++;
		}

		/*
		 * Short delay between readings prevents:
		 * - I2C bus overload
		 * - repeated identical unstable samples
		 */
		Clock_Delay1ms(5);
	}

	/*
	 * If no valid readings were captured, return 0 as failure signal
	 */
	if (valid == 0) return 0;

	/*
	 * Return average of valid measurements for a smoother output
	 */
	return sum / valid;
}

